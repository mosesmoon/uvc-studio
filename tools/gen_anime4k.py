#!/usr/bin/env python3
"""Turns Anime4K's mpv user-shader files into plain GLSL passes for the app.

    gen_anime4k.py <Anime4K/glsl/Upscale> src/Anime4KData.inc

Anime4K (https://github.com/bloc97/Anime4K) is MIT licensed, Copyright (c)
2019-2021 bloc97. Only the Upscale CNN x2 (S and M) networks are used. Each
mpv hook pass becomes one fragment shader; the mpv texture macros
(NAME_tex, NAME_texOff, NAME_pos, NAME_pt, NAME_size) are provided on top of
ordinary samplers so the network code is used unchanged.
"""
import re
import sys
from pathlib import Path

VARIANTS = [("S", "Anime4K_Upscale_CNN_x2_S.glsl"), ("M", "Anime4K_Upscale_CNN_x2_M.glsl")]


def parse(text):
    passes, cur = [], None
    for line in text.splitlines():
        if line.startswith("//!DESC"):
            cur = {"desc": line[8:].strip(), "binds": [], "save": None, "scale": 1, "body": []}
            passes.append(cur)
        elif cur is None:
            continue
        elif line.startswith("//!BIND"):
            cur["binds"].append(line.split()[1])
        elif line.startswith("//!SAVE"):
            cur["save"] = line.split()[1]
        elif line.startswith("//!WIDTH"):
            parts = line.split()[1:]
            cur["scale"] = int(parts[1]) if len(parts) == 3 and parts[2] == "*" else 1
        elif line.startswith("//!"):
            continue
        else:
            cur["body"].append(line)
    return passes


def shader(p):
    out = ["#version 330 core", "in vec2 v_uv;", "out vec4 o;"]
    for b in p["binds"]:
        out += [
            f"uniform sampler2D {b}_raw;",
            f"uniform vec2 {b}_size;",
            f"#define {b}_pos v_uv",
            f"#define {b}_pt (vec2(1.0) / {b}_size)",
            f"#define {b}_tex(pos) texture({b}_raw, pos)",
            f"#define {b}_texOff(off) {b}_tex({b}_pos + {b}_pt * (off))",
        ]
    out += [l for l in p["body"] if l.strip()]
    if p["save"] == "MAIN":
        out.append("void main() { o = vec4(clamp(hook().rgb, 0.0, 1.0), 1.0); }")
    else:
        out.append("void main() { o = hook(); }")
    return "\n".join(out) + "\n"


def cstr(s):
    return 'R"A4K(' + s + ')A4K"'


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        "// Generated by tools/gen_anime4k.py from Anime4K v4 (MIT, Copyright (c) 2019-2021 bloc97).",
        "// Do not edit.",
        "",
    ]
    for tag, fname in VARIANTS:
        passes = parse((src / fname).read_text())
        lines.append(f"static const Anime4KPass kAnime4K_{tag}[] = {{")
        for p in passes:
            binds = ", ".join(f'"{b}"' for b in p["binds"])
            lines.append(f'  {{"{p["save"]}", {p["scale"]}, {len(p["binds"])}, {{{binds}}},')
            lines.append(f"   {cstr(shader(p))}}},")
        lines.append("};")
        lines.append("")
    dst.write_text("\n".join(lines))
    print("wrote", dst)


if __name__ == "__main__":
    main()
