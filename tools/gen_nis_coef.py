#!/usr/bin/env python3
"""Extracts the NVIDIA Image Scaling filter banks for the app.

    gen_nis_coef.py <NVIDIAImageScaling/NIS/NIS_Config.h> src/NISCoef.inc

NVIDIA Image Scaling SDK v1.0.3 is MIT licensed, Copyright (c) 2022 NVIDIA
CORPORATION & AFFILIATES. The 64-phase, 6-tap scaler and USM coefficient
tables are packed into a 4 × 64 RGBA float texture:
  x=0: scaler taps 0-3, x=1: scaler taps 4-5, x=2: USM taps 0-3, x=3: USM taps 4-5.
"""
import re
import sys


def table(src, name):
    m = re.search(r"constexpr float " + name + r"\[kPhaseCount\]\[kFilterSize\] = \{(.*?)\n    \};", src, re.S)
    rows = re.findall(r"\{([^{}]*)\}", m.group(1))
    out = [[float(v.strip().rstrip("f")) for v in r.split(",")] for r in rows]
    assert len(out) == 64 and all(len(r) == 8 for r in out), name
    return out


def main():
    src = open(sys.argv[1]).read()
    scale, usm = table(src, "coef_scale"), table(src, "coef_usm")
    lines = ["// Generated by tools/gen_nis_coef.py from NVIDIA Image Scaling SDK v1.0.3",
             "// (MIT, Copyright (c) 2022 NVIDIA CORPORATION & AFFILIATES). Do not edit.",
             "// 64 rows (phases) x 4 RGBA texels: scaler 0-3, scaler 4-5, USM 0-3, USM 4-5.",
             "static const float kNisCoef[64 * 16] = {"]
    for p in range(64):
        s, u = scale[p], usm[p]
        vals = s[0:4] + [s[4], s[5], 0.0, 0.0] + u[0:4] + [u[4], u[5], 0.0, 0.0]
        lines.append("    " + ", ".join(f"{v:.4f}f" for v in vals) + ",")
    lines.append("};")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")
    print("wrote", sys.argv[2])


if __name__ == "__main__":
    main()
